class Command(BaseCommand):
    help = "잇닥 시드 데이터 적재 (진료과·키워드 사전·응급 키워드·구미권 병원)"

    def add_arguments(self, parser):
        parser.add_argument(
            "--with-hospitals", action="store_true",
            help="데모 병원 25곳도 함께 재적재 (기본: 병원 데이터는 보존 — import_hira 실데이터 보호)",
        )

    def handle(self, *args, **options):
        # 실데이터(import_hira) 보호: 병원은 명시적 요청 또는 빈 DB일 때만 적재
        seed_hospitals = options["with_hospitals"] or not Hospital.objects.exists()

        # 기존 데이터 삭제 후 재적재 (멱등)
        SymptomKeyword.objects.all().delete()
        EmergencyKeyword.objects.all().delete()
        if seed_hospitals:
            Hospital.objects.all().delete()
            Department.objects.all().delete()
        else:
            # 병원 보존 시 진료과도 보존 (M:N 연결 유지) — 키워드만 재연결
            pass

        # 진료과 (HIRA 코드 1:1) — 보존 모드에서는 갱신만
        depts = {}
        for name, (code, desc) in DEPARTMENTS.items():
            depts[name], _ = Department.objects.update_or_create(
                name=name, defaults={"code": code, "description": desc}
            )
        self.stdout.write(self.style.SUCCESS(f"진료과 {len(depts)}개 적재 (HIRA 코드 매핑)"))

        # 증상 키워드 사전 (~500개) + 승인 CSV — 중복(keyword, dept) 제거 후 적재
        # (kw, dept, weight, label) 4-튜플로 정규화해 합친다. label은 DISPLAY_LABELS 우선.
        merged = [(kw, dept, w, DISPLAY_LABELS.get(kw, "")) for kw, dept, w in KEYWORDS]
        approved_count = 0
        if APPROVED_CSV.exists():
            with APPROVED_CSV.open(encoding="utf-8-sig", newline="") as f:
                for r in csv.DictReader(f):
                    dept = (r.get("department") or "").strip()
                    kw = (r.get("keyword") or "").strip()
                    if not kw or dept not in depts:
                        continue  # 알 수 없는 진료과/빈 키워드는 건너뜀
                    try:
                        w = max(1, min(3, int(r.get("weight") or 2)))
                    except ValueError:
                        w = 2
                    merged.append((kw, dept, w, (r.get("label") or "").strip()))
                    approved_count += 1

        seen = set()
        rows = []
        for kw, dept, w, label in merged:
            key = (kw, dept)
            if key in seen:
                continue
            seen.add(key)
            rows.append(SymptomKeyword(keyword=kw, department=depts[dept], weight=w, label=label))
        SymptomKeyword.objects.bulk_create(rows)
        extra = f" (승인 CSV {approved_count}건 포함)" if approved_count else ""
        self.stdout.write(self.style.SUCCESS(f"증상 키워드 {len(rows)}개 적재{extra}"))

        # 응급 키워드
        EmergencyKeyword.objects.bulk_create([
            EmergencyKeyword(keyword=kw, category=cat)
            for kw, cat in EMERGENCY_KEYWORDS
        ])
        self.stdout.write(self.style.SUCCESS(f"응급 키워드 {len(EMERGENCY_KEYWORDS)}개 적재"))

        # 병원 (데모용 — 실데이터 보존 모드면 건너뜀)
        if seed_hospitals:
            for name, addr, lat, lng, phone, ot, ct, dept_names in HOSPITALS:
                h = Hospital.objects.create(
                    name=name, address=addr, latitude=lat, longitude=lng,
                    phone=phone, open_time=ot, close_time=ct,
                )
                h.departments.set([depts[d] for d in dept_names])
            self.stdout.write(self.style.SUCCESS(f"데모 병원 {len(HOSPITALS)}개 적재"))
        else:
            self.stdout.write(f"병원 {Hospital.objects.count()}곳 보존 (실데이터 보호 — 재적재는 --with-hospitals)")
        self.stdout.write(self.style.SUCCESS("시드 데이터 적재 완료!"))
